update public.brands b
set name_zh = s.brand_name_zh
from (
  select distinct on (i.brand_id) i.brand_id, z.brand_name_zh
  from public.catalog_items i
  join oy_zh_seed z on z.source_key = i.source_key
  where i.source = 'oliveyoung' and i.brand_id is not null
  order by i.brand_id, z.source_key
) s
where b.id = s.brand_id;

update public.catalog_items i
set
  name_zh = z.name_zh,
  attributes = i.attributes || jsonb_build_object(
    'translation_status', 'machine_draft',
    'translation_language', 'zh-CN'
  )
from oy_zh_seed z
where i.source = 'oliveyoung' and i.source_key = z.source_key;

commit;

